<h2 class="wp-block-heading">Public comment</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Public comment is offered at regular Business Meetings and Special Called Meetings, and is not permitted at Board Work Sessions or Board Committee Meetings. The sign-up sheet is offered 30 minutes before the meeting and is closed at the start of it.</p>

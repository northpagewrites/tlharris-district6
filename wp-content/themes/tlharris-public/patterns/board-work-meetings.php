<h2 class="wp-block-heading">Public meetings</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>All regular Business Meetings of the Shelby County Board of Education are held at the Frances E. Coe Administration Building, 160 S. Hollywood Street, at 5:30 p.m. on the final Tuesday of each month. The Board holds Work Sessions on Tuesdays one week before all regular business meetings.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>This describes how the Board operates as a body. The district's own calendar is the authoritative schedule.</p>
<!-- /wp:paragraph -->

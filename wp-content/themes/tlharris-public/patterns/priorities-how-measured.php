<h3 class="wp-block-heading">Baseline and target</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>A figure appears only when it comes from a published source, and that source is named. Where no baseline exists, the page says so instead of estimating one.</p>
<!-- /wp:paragraph -->
</div>

<h2 class="wp-block-heading">How progress is measured</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>This is a record of work, not a scorecard. It is written so that a reader can check it rather than take it on trust.</p>
<!-- /wp:paragraph -->

<h2 class="tlharris-keyline">Meet T. L. Harris</h2>
<p class="tlharris-lede">T. L. Harris has lived in Whitehaven for more than 30 years. He came up through Memphis public schools, graduating from East High School, and now helps govern them as the District 6 commissioner on the Memphis-Shelby County Schools Board of Education.</p>
<p>Before he took office on September 1, 2026, he served in the military, worked with the Memphis Police Department, managed cases for young people and families at Youth Villages, worked in youth ministry and served as chief financial officer of a private medical office. For three years he led five community centers for the city's Memphis Gun Down summer program, in neighborhoods including Frayser and Raleigh.</p>

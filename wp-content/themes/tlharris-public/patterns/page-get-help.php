<!-- wp:heading -->
<h2 class="wp-block-heading">1. Start at the school level</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Memphis-Shelby County Schools encourages parents to seek resolution at the school level through the appropriate staff member. A teacher, a counselor or the principal can resolve most questions faster than anyone further away from the classroom.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->

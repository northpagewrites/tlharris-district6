<h2 class="wp-block-heading">When to bring something to the Board</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The Board Office handles matters involving the Board and its business. Board members are elected officials. They are not employees of the school system, and they do not have individual offices at the district's Central Office.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>In practice that means questions about policy, about Board decisions, and about how the district is being held to account belong at the Board level. Questions about a particular classroom, a staffing decision or a day-to-day school operation are handled by the school and the responsible district department, and go faster there.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Want to address the Board?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Public comment is offered at regular Business Meetings and Special Called Meetings. It is not permitted at Board Work Sessions or Board Committee Meetings.</p>
<!-- /wp:paragraph -->
<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>A sign-up sheet is offered 30 minutes before each Business Meeting and Special Called Meeting, at the entryway table just past the security checkpoint.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>The sheet is closed and removed at the start of the meeting. Only those who sign up before the meeting begins may address the Board.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>You give your name and home address, and the organization you represent if that applies.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Speakers share a 30-minute slot in equal increments, not to exceed three minutes each. No speaker may yield time to another speaker.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>The period ends after 30 minutes, or when everyone signed up has been heard, whichever comes first.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->
<!-- wp:paragraph -->
<p>The district publishes the full rules: <a href="https://www.scsk12.org/board/?PN=49">Addressing the Board</a>.</p>

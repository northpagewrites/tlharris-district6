<!-- wp:paragraph -->
<p>This is the website of T. L. Harris, the District 6 commissioner on the Memphis-Shelby County Schools Board of Education. This page explains what information the site collects and how it is used. In short: the site does not ask you to create an account, does not show advertising, and does not sell or rent information about visitors.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">What the site collects</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Like almost every website, the server that hosts this site automatically records basic technical details when a page is requested, such as the date and time, the page you asked for, your browser type and your IP address. This is used to keep the site secure and running. It is not used to identify individual visitors.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>The site has no accounts, comments or sign-up forms at this time, and it does not use advertising trackers. If a form is added later, this page will be updated to say what it collects and why.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Cookies</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>This site does not use cookies to track you. Some outside sites linked from these pages, such as Facebook, set their own cookies once you visit them.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Contacting the office</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>If you email, call or write to the MSCS Board Office or to this office, we receive what you send, such as your name, contact details and message. It is used to respond to you and to carry out the work of the office.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Messages sent to or from a public official about public business may be public records under the Tennessee Public Records Act, which means they can be requested and released. Please do not include Social Security numbers, medical details or private student information in a message.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Students and student information</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>For a question about a particular student, please contact the student’s school or Memphis-Shelby County Schools directly. Student records are protected by law and should not be sent through this website.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Links to other sites</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>This site links to the Memphis-Shelby County Schools website, BoardDocs, news outlets and Facebook. Those sites have their own privacy practices, and this page does not cover them. Anything you post on the Facebook page linked from this site is governed by Facebook’s terms and privacy policy.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Children</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>This site is meant for adults and is not directed to children under 13. It does not knowingly collect information from children.</p>

<p class="tlharris-meta">Last updated September 25, 2026</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>I want everyone in District 6 to be able to use this website, including people who use screen readers, keyboards, voice control, magnification or other assistive technology.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Our goal</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>My goal is for this site to meet the Web Content Accessibility Guidelines (WCAG) 2.1, Level AA.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">What is built in</h2>
<!-- /wp:heading -->
<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>A “Skip to content” link at the top of every page, for keyboard and screen reader users.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Text and background colors checked for enough contrast to read comfortably.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Headings, navigation and page sections in a clear order, so assistive technology can move through them.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Links and buttons that can be reached and used with a keyboard, with a visible outline showing where you are.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Pages that resize and reflow for larger text and for phone screens.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>A photo slideshow on the home page that stays still for people whose device is set to reduce motion.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Video</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Video on the site uses the standard player controls, which work with a keyboard. Not every video has captions yet, and my office is working to add them. If you need captions or a written version of a video, please ask.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">What I do not control</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Some pages link to documents and sites run by others, such as PDFs, BoardDocs and the Memphis-Shelby County Schools website. Their accessibility is the responsibility of the people who run them.</p>
<!-- /wp:paragraph -->
